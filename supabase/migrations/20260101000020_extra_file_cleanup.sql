-- ============================================================
-- Удаление файла доп. работы после проверки
--
-- При выставлении баллов приложение удаляет файл из бакета
-- extra_submissions и очищает file_path. Оценка, имя файла,
-- размер и дата сдачи остаются в строке, а file_deleted_at
-- позволяет показать «удалён после проверки».
--
-- Выполнить после 20260101000019_extra_leaderboard_avatars.sql.
-- Миграция идемпотентна: её можно запускать повторно.
-- ============================================================

alter table public.extra_submissions
  add column if not exists file_deleted_at timestamptz;

comment on column public.extra_submissions.file_deleted_at is
  'Когда файл удалён из хранилища после проверки. Оценка и метаданные работы сохраняются.';

notify pgrst, 'reload schema';
